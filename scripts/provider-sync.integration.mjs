import fs from "node:fs/promises";
import path from "node:path";
import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { execFileSync } from "node:child_process";
const service = path.resolve(process.env.JOKERDECK_PROVIDER_SERVICE);
const runner = path.resolve("src-tauri/src/provider_sync.mjs");
const fixtureRoot = path.resolve("node_modules/.cache/provider-fixtures");
await fs.mkdir(fixtureRoot, { recursive: true });
const home = await fs.mkdtemp(path.join(fixtureRoot, "sync-"));
const thread = "01a0f476-f4c7-7523-b71e-32dd083b2b5b";
await fs.mkdir(path.join(home, "sessions"));
const rollout = path.join(home, "sessions", `rollout-2026-10-08T00-00-00-${thread}.jsonl`);
const body = '\n{"type":"response_item","payload":{"role":"user","content":[{"type":"input_text","text":"keep my chat"}]}}\n';
await fs.writeFile(rollout, JSON.stringify({ type: "session_meta", payload: { id: thread, model_provider: "old-provider", cwd: fixtureRoot } }) + body);
const config = 'model_provider = "new-provider"\nmodel = "keep-history-model"\n[model_providers.new-provider]\nname = "New"\nbase_url = "http://127.0.0.1:8788/v1"\n';
await fs.writeFile(path.join(home, "config.toml"), config);
const dbPath = path.join(home, "state_5.sqlite");
const db = new DatabaseSync(dbPath);
db.exec("CREATE TABLE threads (id TEXT PRIMARY KEY, model_provider TEXT, cwd TEXT, rollout_path TEXT, has_user_event INTEGER, updated_at INTEGER, archived INTEGER)");
db.prepare("INSERT INTO threads VALUES (?,?,?,?,?,?,?)").run(thread, "old-provider", fixtureRoot, rollout, 1, 100, 0);
db.close();
const run = (action, backup) => JSON.parse(execFileSync(process.execPath, [runner, service, action, home, ...(backup ? [backup] : [])], { encoding: "utf8" }));
assert.equal(run("status").currentProvider, "new-provider");
const synced = run("sync");
assert.equal(synced.sqliteRowsUpdated, 1);
const content = await fs.readFile(rollout, "utf8");
assert.equal(JSON.parse(content.split("\n")[0]).payload.model_provider, "new-provider");
assert.equal(content.slice(content.indexOf("\n")), body);
assert.equal(await fs.readFile(path.join(home, "config.toml"), "utf8"), config);
let check = new DatabaseSync(dbPath);
assert.equal(check.prepare("SELECT model_provider FROM threads").get().model_provider, "new-provider");
check.close();
const status = run("status");
assert.ok(Array.isArray(status.backups));
assert.ok(status.backups.length);
run("restore", path.basename(synced.backupDir));
check = new DatabaseSync(dbPath);
assert.equal(check.prepare("SELECT model_provider FROM threads").get().model_provider, "old-provider");
check.close();
assert.equal(JSON.parse((await fs.readFile(rollout, "utf8")).split("\n")[0]).payload.model_provider, "old-provider");
assert.equal(await fs.readFile(path.join(home, "config.toml"), "utf8"), config);
console.log("PASS: Provider sync, SQLite, preserved chat/config, backup and restore");
